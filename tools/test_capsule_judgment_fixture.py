"""INT-STUDIUM-004 — the capsule-grounded judgment fixture must plant a DECIDABLE flaw.

`fixtures/capsule-judgment-demo` is generated by `tools/build_capsule_judgment_demo.py` from a
real run of `fixtures/capsule-demo`. The planted flaw "la demi-vie depasse une heure" can only be
scored if the run says what unit the half-life is in. The capsule's time axis was
`np.linspace(0.0, 10.0, 50)` with `xlabel("t")` — dimensionless — so `half_life=1.6457` was a bare
number, and the authored `model_correction` concluded "pas une heure" from it, which is the same
category error the scene plants. A learner who answered "you cannot tell without a unit" was right
and was graded wrong.

The unit lives in ONE place, the capsule that measures it. These tests read the committed fixture
(what a learner actually plays), not the generator, so a regeneration that drops the unit fails
here.

Run: .venv/bin/python -m pytest tools/test_capsule_judgment_fixture.py -q
"""
import json
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUNDLE = os.path.join(REPO, "fixtures", "capsule-judgment-demo", "lesson.json")
SCENES = os.path.join(REPO, "fixtures", "capsule-judgment-demo", "scenes.json")
CAPSULE_RUN = os.path.join(REPO, "fixtures", "capsule-demo", "scripts", "run.py")

#: The half-life the demo capsule reports, and the largest value in seconds that is still not
#: "more than an hour" — the comparison the planted flaw asks the learner to make.
HALF_LIFE = 1.6457
ONE_HOUR_S = 3600


def _spot_scenes():
    bundle = json.loads(open(BUNDLE, encoding="utf-8").read())
    return [s for s in bundle["scenes"] if s.get("type") == "spot_the_flaw"]


def test_the_capsule_declares_the_unit_of_its_time_axis():
    """The unit is a property of the measurement, so it is fixed where the measurement is made."""
    src = open(CAPSULE_RUN, encoding="utf-8").read()
    assert "half_life={half_life:.4f} s" in src, "the landmark must carry the half-life's unit"
    assert re.search(r'xlabel\("t \(s\)"\)', src), "the figure axis must name the unit too"


def test_every_planted_demi_vie_flaw_is_decidable_against_the_landmark():
    """`la demi-vie depasse une heure` is a flaw only if the landmark says 1.6457 SECONDS."""
    scenes = _spot_scenes()
    assert scenes, "the demo bundle must still carry its spot_the_flaw scenes"
    for scene in scenes:
        landmark = scene["reference_result"]["landmark"]
        m = re.search(r"half_life=([0-9.]+)\s*(\S+)", landmark)
        assert m, f"{scene['id']}: landmark states no half-life: {landmark!r}"
        value, unit = float(m.group(1)), m.group(2)
        assert unit == "s", f"{scene['id']}: half-life carries no unit ({landmark!r})"
        assert value == HALF_LIFE and value < ONE_HOUR_S, (
            f"{scene['id']}: {value} {unit} does not settle the planted claim"
        )


def test_the_model_correction_reasons_from_the_unit_it_now_has():
    """The correction used to assert `pas une heure` about a dimensionless number. It may only
    deny the hour by naming the unit that makes the denial true."""
    for scene in _spot_scenes():
        correction = scene["model_correction"]
        if "heure" not in correction:
            continue
        assert "unite de temps" not in correction, (
            f"{scene['id']}: the correction still hedges the unit it is concluding from"
        )
        assert re.search(r"1[.,]6\d*\s*s\b", correction), (
            f"{scene['id']}: the correction denies the hour without naming seconds: {correction!r}"
        )


def test_the_two_generated_files_agree_on_the_landmark():
    """`scenes.json` and `lesson.json` are written by the same run; a partial regeneration that
    updated one and not the other would leave two different answer keys in the corpus."""
    from_bundle = {s["id"]: s["reference_result"]["landmark"] for s in _spot_scenes()}
    loose = json.loads(open(SCENES, encoding="utf-8").read())
    from_scenes = {s["id"]: s["reference_result"]["landmark"] for s in loose}
    assert from_bundle == from_scenes
